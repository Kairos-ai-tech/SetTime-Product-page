#!/usr/bin/env node
// Renders the pricing pages from pricing/pricing-content.mjs:
//   pricing/index.html     (繁體中文, /pricing/)
//   en/pricing/index.html  (English, /en/pricing/)
//
//   node scripts/build-pricing.mjs          write files
//   node scripts/build-pricing.mjs --check  exit 1 if any file is stale (CI)
//
// Each figure that changes with the currency or billing toggle is written into
// the page in all four states (data-v-<currency>-<billing>); pricing/pricing.js
// only swaps between them, so the page works without JS in its default state.
// Copy exists only in English and 繁中, so no other locale gets a pricing page.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://settime.kairosaitech.com";
const check = process.argv.includes("--check");
const { PLACEHOLDERS, PRICES, LINKS, COPY } = await import(pathToFileURL(path.join(root, "pricing/pricing-content.mjs")).href);

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const STATES = [["usd", "yearly"], ["usd", "monthly"], ["ntd", "yearly"], ["ntd", "monthly"]];
const hasToken = (s) => /\{(price|monthly|yearly|overage|seat|pilot|ntdSuffix)\}/.test(s);

function fill(tpl, lang, plan, cur) {
  const p = plan && PRICES[plan] ? PRICES[plan][cur] : {};
  const vals = {
    yearly: p.yearly, monthly: p.monthly, overage: p.overage,
    seat: PRICES.extraSeat[cur], pilot: PRICES.pilot[cur],
    ntdSuffix: cur === "ntd" ? COPY[lang].ntdSuffix : "",
  };
  return tpl.replace(/\{(\w+)\}/g, (m, k) => (k in vals && vals[k] !== undefined ? esc(vals[k]) : m));
}

// Text (escaped) or trusted markup (the price line), with per-state variants when it has figures.
function variant(tag, tpl, lang, { plan = null, cls = "", html = false, billingTpl = null, defCur } = {}) {
  const base = html ? (s) => s : esc;
  const render = (cur, bill) => fill(base(billingTpl ? billingTpl[bill] : tpl), lang, plan, cur);
  const c = cls ? ` class="${cls}"` : "";
  if (!billingTpl && !hasToken(tpl)) return `<${tag}${c}>${base(tpl)}</${tag}>`;
  const attrs = STATES.map(([cur, bill]) => ` data-v-${cur}-${bill}="${esc(render(cur, bill))}"`).join("");
  return `<${tag}${c} data-variant${attrs}>${render(defCur, "yearly")}</${tag}>`;
}

function page(lang) {
  const t = COPY[lang];
  const L = LINKS[lang];
  const defCur = t.defaultCurrency;
  const other = t.nav.otherLang;
  const url = SITE + t.path;
  const legalHref = PLACEHOLDERS.legal;
  const privacyLink = `<a href="${esc(legalHref.privacy)}" data-placeholder>${esc(t.faq.privacyLinkText)}</a>`;
  const faqPrivacy = esc(PLACEHOLDERS.faqPrivacy[lang]).replace("{privacy}", privacyLink);
  const seg = (name, opts, labels, active) =>
    `<div class="seg" role="group" aria-label="${esc(labels.label)}" data-toggle="${name}">` +
    opts.map((o) => `<button type="button" data-value="${o}" aria-pressed="${o === active}">${esc(labels[o])}</button>`).join("") +
    `</div>`;

  const plans = t.plans.map((pl) => {
    const priced = !!PRICES[pl.id];
    return `
        <article class="plan${pl.popular ? " plan--popular" : ""}" id="plan-${pl.id}">
          ${pl.popular ? `<p class="badge">${esc(t.popular)}</p>` : ""}
          <h3>${esc(pl.name)}</h3>
          <p class="tagline">${esc(pl.tagline)}</p>
          ${priced ? variant("p", "", lang, { plan: pl.id, cls: "price", html: true, billingTpl: t.price, defCur }) : ""}
          <ul>
            ${pl.features.map((f) => variant("li", f, lang, { plan: pl.id, defCur })).join("\n            ")}
          </ul>
          <a class="btn${pl.popular ? " btn--primary" : ""}" href="${esc(L[pl.cta.to])}">${esc(pl.cta.label)}</a>
        </article>`;
  }).join("");

  const faq = t.faq.items.map(([q, a]) => {
    const body = a === "{faqPrivacy}"
      ? `<p data-placeholder="faq-privacy">${faqPrivacy}</p>`
      : variant("p", a, lang, { defCur });
    return `
        <details>
          <summary>${esc(q)}</summary>
          ${body}
        </details>`;
  }).join("");

  return `<!DOCTYPE html>
<!-- Generated by scripts/build-pricing.mjs from pricing/pricing-content.mjs. Do not edit by hand. -->
<html lang="${t.htmlLang}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${esc(t.meta.title)}</title>
  <meta name="description" content="${esc(t.meta.description)}">
  <!-- DRAFT: keep noindex until the page is approved for launch; then switch to
       "index, follow" in build-pricing.mjs and add both URLs to sitemap.xml. -->
  <meta name="robots" content="noindex, nofollow">
  <link rel="canonical" href="${url}">
  <link rel="alternate" hreflang="zh-Hant" href="${SITE}${COPY.zh.path}">
  <link rel="alternate" hreflang="en" href="${SITE}${COPY.en.path}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="SetTime">
  <meta property="og:title" content="${esc(t.meta.title)}">
  <meta property="og:description" content="${esc(t.meta.description)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${SITE}/assets/settime-og-card.jpg">
  <meta name="twitter:card" content="summary_large_image">
  <link rel="icon" type="image/png" href="/assets/settime-favicon.png">
  <link rel="stylesheet" href="/pricing/pricing.css">
  <script src="/pricing/pricing.js" defer></script>
</head>
<body data-default-currency="${defCur}">
  <header class="top">
    <a class="logo" href="${L.home}"><img src="/assets/settime-logo-64.jpg" alt="" width="28" height="28"> ${esc(t.nav.product)}</a>
    <nav aria-label="Language">
      <a href="${other.href}" hreflang="${other.lang}" lang="${other.lang}">${esc(other.label)}</a>
    </nav>
  </header>
  <main>
    <section class="hero">
      <h1>${esc(t.hero.heading)}</h1>
      <p class="lede">${esc(t.hero.lead)}</p>
      <div class="toggles">
        ${seg("billing", ["yearly", "monthly"], t.toggles.billing, "yearly")}
        ${seg("currency", t.toggles.currency.order, t.toggles.currency, defCur)}
      </div>
      ${t.hero.taxNote ? `<p class="tax-note" data-currency-only="ntd"${defCur === "ntd" ? "" : " hidden"}>${esc(t.hero.taxNote)}</p>` : ""}
    </section>

    <section class="plans" aria-label="Plans">${plans}
    </section>

    <section class="includes">
      <h2>${esc(t.includes.heading)}</h2>
      <ul>
        ${t.includes.items.map((i) => `<li>${esc(i)}</li>`).join("\n        ")}
      </ul>
    </section>

    <section class="pilot" id="pilot">
      <p class="eyebrow">${esc(t.pilot.label)}</p>
      <h2>${esc(t.pilot.heading)}</h2>
      ${variant("p", t.pilot.body, lang, { defCur })}
      <a class="btn btn--primary" href="${esc(L.pilot)}">${esc(t.pilot.cta)}</a>
    </section>

    <section class="why">
      <h2>${esc(t.why.heading)}</h2>
      <ul>
        ${t.why.items.map(([b, r]) => `<li><strong>${esc(b)}</strong>${esc(r)}</li>`).join("\n        ")}
      </ul>
    </section>

    <section class="faq">
      <h2>${esc(t.faq.heading)}</h2>${faq}
    </section>

    <section class="closing">
      <h2>${esc(t.closing.heading)}</h2>
      <p>${esc(t.closing.body)}</p>
      <p class="actions">
        <a class="btn btn--primary" href="${esc(L.pilot)}">${esc(t.closing.pilot)}</a>
        <a class="btn" href="${esc(L.contact)}">${esc(t.closing.contact)}</a>
      </p>
    </section>
  </main>
  <footer>
    <nav aria-label="Legal">
      <a href="${esc(legalHref.terms)}" data-placeholder>${esc(t.legal.terms)}</a> ·
      <a href="${esc(legalHref.refund)}" data-placeholder>${esc(t.legal.refund)}</a> ·
      <a href="${esc(legalHref.privacy)}" data-placeholder>${esc(t.legal.privacy)}</a>
    </nav>
    <p>${esc(t.rights)}</p>
  </footer>
</body>
</html>
`;
}

const out = new Map([
  ["pricing/index.html", page("zh")],
  ["en/pricing/index.html", page("en")],
]);

let stale = 0;
for (const [file, content] of out) {
  const full = path.join(root, file);
  const current = fs.existsSync(full) ? fs.readFileSync(full, "utf8") : null;
  if (current === content) continue;
  stale++;
  if (check) console.error(`stale: ${file}`);
  else {
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, content);
    console.log(`wrote ${file}`);
  }
}
if (check && stale) {
  console.error("run: node scripts/build-pricing.mjs");
  process.exit(1);
}
if (!stale) console.log("pricing pages up to date");
